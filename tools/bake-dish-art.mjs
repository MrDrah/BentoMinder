#!/usr/bin/env node
// Authoring-time tool (not shipped, not run by the build): runs the seeded generator of the approved
// preview design/preview/illustrations.html once and writes the BAKED, minified path data to
// src/ui/dish-art/art-data.ts. Output is deterministic (seed = dish index x 977 + 13), so re-running gives
// the same drawings. Minify: absolute C -> relative c, no redundant separators, short class names.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const html = readFileSync(join(root, 'design', 'preview', 'illustrations.html'), 'utf8');
const script = html.slice(html.indexOf('<script>') + 8, html.indexOf('for(const th of'));
const { svg, keys } = new Function(`${script}\nreturn {svg, keys: Object.keys(D)};`)();

const num = (n) => String(Math.round(n * 10) / 10).replace(/^(-?)0\./, '$1.');
const join2 = (list) => list.reduce((s, n) => s + (s === '' || n.startsWith('-') ? '' : ' ') + n, '');

/** Minify one path `d` (commands M C Z q t L, absolute or relative as generated) to relative commands. */
function minPath(d) {
  const tokens = d.match(/[A-Za-z]|-?\d*\.?\d+/g);
  let i = 0;
  let cx = 0;
  let cy = 0;
  let sx = 0;
  let sy = 0;
  let out = '';
  let last = '';
  const emit = (cmd, nums) => {
    const body = join2(nums.map(num));
    out += cmd === last ? (body.startsWith('-') ? '' : ' ') + body : cmd + body;
    last = cmd;
  };
  while (i < tokens.length) {
    const cmd = tokens[i++];
    const take = (n) => tokens.slice(i, (i += n)).map(Number);
    if (cmd === 'Z') {
      out += 'z';
      last = 'z';
      cx = sx;
      cy = sy;
    } else if (cmd === 'M') {
      const [x, y] = take(2);
      out += `M${num(x)}${num(y).startsWith('-') ? '' : ' '}${num(y)}`;
      last = 'M';
      cx = sx = x;
      cy = sy = y;
    } else if (cmd === 'L') {
      while (i < tokens.length && !/[A-Za-z]/.test(tokens[i])) {
        const [x, y] = take(2);
        emit('l', [x - cx, y - cy]);
        cx = x;
        cy = y;
      }
    } else if (cmd === 'C') {
      while (i < tokens.length && !/[A-Za-z]/.test(tokens[i])) {
        const [a, b, c, d2, x, y] = take(6);
        emit('c', [a - cx, b - cy, c - cx, d2 - cy, x - cx, y - cy]);
        cx = x;
        cy = y;
      }
    } else if (cmd === 'c' || cmd === 'q' || cmd === 't' || cmd === 'l' || cmd === 's') {
      const size = { c: 6, q: 4, s: 4, t: 2, l: 2 }[cmd];
      while (i < tokens.length && !/[A-Za-z]/.test(tokens[i])) {
        const v = take(size);
        emit(cmd, v);
        cx += v[size - 2];
        cy += v[size - 1];
      }
    } else throw new Error(`unsupported path command ${cmd} in ${d}`);
  }
  return out;
}

const TOK = { a1: 'a', a2: 'a', steam1: 's1', steam2: 's2', twk1: 'k1', twk2: 'k2' };
const shortCls = (c) => (c === 'l nf' ? 'o' : c.split(' ').map((t) => TOK[t] ?? t).join(' '));

const data = {};
for (const key of keys) {
  const s = svg(key);
  const inner = s.slice(s.indexOf('>') + 1, s.lastIndexOf('</svg>'));
  let body = inner
    .replace(/ d="([^"]*)"/g, (_, d) => ` d="${minPath(d)}"`)
    .replace(/class="([^"]*)"/g, (_, c) => `class="${shortCls(c)}"`)
    .replace(/ stroke-width="(\d+(?:\.\d+)?)"/g, (_, w) => ` stroke-width="${w}"`)
    .replace(/<path class="(\w+)" d="([^"]*)"\/>/g, '<path class="$1" d="$2"/>');
  data[key] = body;
}

const lines = keys.map((k) => '  ' + JSON.stringify(k) + ': `' + data[k] + '`,');
const ts = `// GENERATED by tools/bake-dish-art.mjs from design/preview/illustrations.html (seeded generator, baked once).
// Static, trusted markup: 18 hand-drawn dish illustrations in a 120 x 120 box (design/illustrations.md §2b, §3).
import type { DishType } from '../../domain/schema/dish-type.ts';

export const ART: Record<DishType, string> = {
${lines.join('\n')}
};
`;
writeFileSync(join(root, 'src', 'ui', 'dish-art', 'art-data.ts'), ts);
console.log(`wrote src/ui/dish-art/art-data.ts (${ts.length} bytes)`);
