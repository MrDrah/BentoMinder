import { readFileSync, writeFileSync } from 'node:fs';
const rows = new Map();
for (const line of readFileSync('design/copy.md', 'utf8').split('\n')) {
  if (!line.startsWith('| debug.')) continue;
  const c = line.split('|').map((s) => s.trim());
  rows.set(c[1], [c[2], c[3]]);
}
rows.delete('debug.marker');
const q = (s) => JSON.stringify(s);
const body = (i) => [...rows].map(([k, v]) => `  ${q(k)}: ${q(v[i])},`).join('\n');
writeFileSync('src/debug/catalog.ts', `// Dev-only strings (design/copy.md §18), generated by docs/dev/_scratch/gen-debug-catalog.mjs. Imported only by\n// the debug module, so the production bundle contains none of them (BR-24).\nexport const debugCatalog = {\n  ja: {\n${body(0)}\n  },\n  en: {\n${body(1)}\n  },\n} as const;\n\nexport type DebugKey = keyof (typeof debugCatalog)['ja'];\n`);
console.log(rows.size);
